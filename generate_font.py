# Now render the sprite sheet
img = Image.new('RGBA', (SHEET_W, SHEET_H), (0, 0, 0, 0))

for code in range(128):
    col = code % COLS
    row = code // COLS
    ox = col * CHAR_W
    oy = row * CHAR_H
    glyph = glyphs[code]
    for gy, line in enumerate(glyph):
        for gx, ch in enumerate(line):
            if ch == '#':
                img.putpixel((ox + gx, oy + gy), (255, 255, 255, 255))

output_path = "/root/code/m8/app/src/main/assets/m8_font.png"
img.save(output_path)
