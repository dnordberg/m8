from PIL import Image

# Sheet dimensions: 16 chars * 8px = 128px wide, 8 rows * 10px = 80px tall
CHAR_W = 8
CHAR_H = 10
COLS = 16
ROWS = 8
SHEET_W = COLS * CHAR_W   # 128
SHEET_H = ROWS * CHAR_H   # 80

# Define each character as a list of strings, each string is a row of the glyph.
# '.' = transparent, '#' = white pixel
# Characters are 8 wide, 10 tall (some may use fewer rows, padded with blanks)

def make_empty():
    return [
        "........",
        "........",
        "........",
        "........",
        "........",
        "........",
        "........",
        "........",
        "........",
        "........",
    ]

def pad(rows):
    """Pad/trim glyph data to exactly CHAR_H rows of CHAR_W width."""
    result = []
    for r in rows:
        r = r.ljust(CHAR_W, '.')[:CHAR_W]
        result.append(r)
    while len(result) < CHAR_H:
        result.append('.' * CHAR_W)
    return result[:CHAR_H]

